import * as THREE from 'three';

export type PartId =
  | 'frame'
  | 'kickstand'
  | 'controller'
  | 'wiringHarness'
  | 'rearSwingarm'
  | 'rearShocks'
  | 'rearWheel'
  | 'rearFender'
  | 'battery'
  | 'frontFork'
  | 'frontFender'
  | 'frontWheel'
  | 'handlebars'
  | 'headlight'
  | 'driverSeat'
  | 'passengerSeat'
  | 'backrest';

export interface PartInfo {
  id: PartId;
  name: string;
  category: 'chassis' | 'powertrain' | 'steering' | 'seating' | 'body' | 'electronics';
  description: string;
  weightKg: number;
  material: string;
  torqueSpec?: string;
  toolsNeeded: string[];
  explodedOffset: [number, number, number]; // Vector direction when exploded
  assemblyStep: number; // 1 to 9
  subPartsCount: number;
  highlightColor?: string;
}

export interface ConnectionPoint {
  id: string;
  name: string;
  partId: PartId;
  stepNumber: number;
  position: [number, number, number]; // 3D coordinates on parent/chassis
  normal: [number, number, number]; // vector along which bolt or part slides
  type: 'bolt' | 'pivot' | 'terminal' | 'clamp' | 'latch' | 'axle';
  spec: string;
  description: string;
}

export interface AssemblyStep {
  stepNumber: number;
  title: string;
  subtitle: string;
  partIds: PartId[];
  tools: string[];
  fasteners: string;
  instructions: string[];
  cautionNote?: string;
  connectionPoints: ConnectionPoint[];
  cameraPreset: {
    position: [number, number, number];
    target: [number, number, number];
  };
}

export interface ScooterCustomization {
  bodyColor: string;
  bodyFinish: 'gloss' | 'matte' | 'metallic';
  seatColor: string;
  rimColor: string;
}

